#!/usr/bin/env bash
# Joins every migration, in order, into supabase/all-migrations.sql so a database that's behind can be
# brought up to date with one paste into the Supabase SQL editor. Every migration is safe to run again,
# so it doesn't matter which ones you have already run. Re-run this after adding a migration.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/all-migrations.sql
{
  echo "-- All migrations in order (generated by scripts/build-all-migrations.sh; don't edit)."
  echo "-- Safe to run on a database that already has some or all of them."
  for f in supabase/migrations/*.sql; do
    printf '\n-- ===== %s =====\n' "$(basename "$f")"
    cat "$f"
  done
} > "$out"
echo "Wrote $out ($(wc -c < "$out") bytes)"
